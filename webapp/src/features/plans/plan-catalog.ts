import type { RationEntry } from '@/features/mentor'
import type { AuthoredPlan, PlanGoal } from '@/platform/authored-plans'

export const CATALOG_PLAN_ID_PREFIX = 'catalog_'
export const CATALOG_PLAN_SOURCE = 'Каталог'

export type CatalogPlan = {
  id: string
  title: string
  description: string
  goal: PlanGoal
  coverImage: string
  kcal: number
  days: RationEntry[]
}

type CatalogDish = {
  title: string
  ingredients: string
  steps: string[]
  image: string
  kcal: number
  protein: number
  fat: number
  carbs: number
}

type CatalogMeal = RationEntry['meals'][number]

export function isCatalogPlanId(planId: string) {
  return planId.startsWith(CATALOG_PLAN_ID_PREFIX)
}

export function catalogPlanById(planId: string) {
  return PLAN_CATALOG.find((plan) => plan.id === planId) ?? null
}

export function authoredCloneOfCatalog(
  plans: readonly AuthoredPlan[],
  catalogId: string,
) {
  return plans.find((plan) => plan.sourceCatalogId === catalogId) ?? null
}

function serve(dish: CatalogDish, slot: CatalogMeal['slot']): CatalogMeal {
  return {
    slot,
    title: dish.title,
    ingredients: dish.ingredients,
    steps: dish.steps,
    image: dish.image,
    kcal: dish.kcal,
    protein: dish.protein,
    fat: dish.fat,
    carbs: dish.carbs,
  }
}

function dayTotals(meals: readonly CatalogMeal[]) {
  return meals.reduce(
    (sum, meal) => ({
      kcal: sum.kcal + meal.kcal,
      protein: sum.protein + meal.protein,
      fat: sum.fat + meal.fat,
      carbs: sum.carbs + meal.carbs,
    }),
    { kcal: 0, protein: 0, fat: 0, carbs: 0 },
  )
}

function catalogDayDescription(meals: readonly CatalogMeal[]): string {
  const titleOf = (slot: CatalogMeal['slot']) =>
    meals.find((meal) => meal.slot === slot)?.title.trim() ?? ''
  const breakfast = titleOf('Завтрак')
  const lunch = titleOf('Обед')
  const snack = titleOf('Перекус')
  const dinner = titleOf('Ужин')
  const first = [
    breakfast ? `Завтрак — ${breakfast}` : '',
    lunch ? `обед — ${lunch}` : '',
  ]
    .filter(Boolean)
    .join(', ')
  const second = [
    snack ? `Перекус — ${snack}` : '',
    dinner ? `ужин — ${dinner}` : '',
  ]
    .filter(Boolean)
    .join(', ')
  if (first && second) return `${first}.\n${second.charAt(0).toUpperCase()}${second.slice(1)}.`
  if (first) return `${first}.`
  if (second) return `${second.charAt(0).toUpperCase()}${second.slice(1)}.`
  return ''
}

function catalogDay(
  planId: string,
  goal: PlanGoal,
  index: number,
  meals: CatalogMeal[],
): RationEntry {
  const totals = dayTotals(meals)
  return {
    id: `${planId}:d${index + 1}`,
    title: `День ${index + 1}`,
    description: catalogDayDescription(meals),
    goal,
    days: 1,
    mealsPerDay: meals.length,
    image: meals[0]?.image ?? '',
    source: CATALOG_PLAN_SOURCE,
    meals,
    ...totals,
  }
}

function catalogPlan(input: {
  id: string
  title: string
  description: string
  goal: PlanGoal
  coverImage: string
  days: CatalogMeal[][]
}): CatalogPlan {
  const days = input.days.map((meals, index) =>
    catalogDay(input.id, input.goal, index, meals),
  )
  const kcal = Math.round(days.reduce((sum, day) => sum + day.kcal, 0) / days.length)
  return {
    id: input.id,
    title: input.title,
    description: input.description,
    goal: input.goal,
    coverImage: input.coverImage,
    kcal,
    days,
  }
}

